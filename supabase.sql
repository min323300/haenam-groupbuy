create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 created_at timestamptz default now(),
 name text not null, phone text not null, qty integer default 1,
 address text not null, memo text,
 status_call boolean default false,
 status_paid boolean default false,
 status_notice boolean default false,
 status_shipping boolean default false
);
create table if not exists public.settings (
 id integer primary key,
 title text, description text, price integer, image_url text
);
